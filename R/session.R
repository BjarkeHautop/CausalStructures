# Design notes:
# - CausalStructures.jl is compiled with juliac by jlbind, into one library with
#   the binding packages of every installed package that uses jlbind; the
#   binding package is inst/julia (`csjl`). There is no Julia session to start
#   and nothing to precompile.
# - Each `@rcall` entrypoint `csjl_jl_<name>_<nargs>` takes and returns R
#   objects and converts them itself through R's C API, so a call is a single
#   `.Call`.
#   A failure inside the library comes back as a `jlbind_error` object and is
#   raised by the package's own routine, so R never unwinds through Julia
#   frames.
# - A graph cannot cross into R as a value, so R holds an external pointer to
#   it (`RRef{CausalGraph}`), with class `cgraph` and a finalizer that releases
#   the library's reference.
# - Every exported function is a single `.Call(C_jl_<name>, ...)` on a routine
#   registered by the package's own shared object (src/jlbind.c, generated by
#   jlbind), which forwards to the library; jlbind::bind_client() binds those
#   when the package is loaded. Graphs go to the library as `cgraph`s, node
#   sets as character vectors. The entrypoints are `jl_`-prefixed so that the
#   R functions jlbind generates for them (R/jlbind-wrappers.R) do not clash
#   with the hand-written ones; R calls the routines directly.

#' Package options
#'
#' `CausalStructures` reads the following [options()]:
#'
#' \describe{
#'   \item{`CausalStructures.open`}{Logical, default `TRUE`. Default for the
#'     `open` argument of [ancestors()], [descendants()],
#'     [possible_ancestors()], [possible_descendants()], [anteriors()], and
#'     [posteriors()]: `TRUE` (open definition) excludes the query node
#'     itself from the result, `FALSE` (closed definition) includes it.}
#' }
#'
#' The algorithms run in a library compiled from CausalStructures.jl by
#' [install_backend()], shared with the other installed packages that call
#' Julia through 'jlbind'. The number of Julia threads is read from the
#' `JULIA_NUM_THREADS` environment variable (a number or `"auto"`) when that
#' library is loaded, so set it before loading the package. The library is
#' looked up in the `JLBIND_LIBRARY` environment variable first (a path to a
#' library built with [jlbind::build_library()]), then, when the package is
#' loaded with `pkgload::load_all()`, in `.jlbind/` in its sources (where
#' `jlbind::build_library()` writes by default), then where
#' [install_backend()] builds it.
#'
#' @name CausalStructures_options
NULL

#' Is the compiled CausalStructures.jl library available?
#'
#' @return A logical scalar.
#' @export
julia_ready <- function() {
  jlbind::is_bound("CausalStructures")
}

#' Check that the compiled CausalStructures.jl library is available
#'
#' Raises an error saying why the library is not available, if it is not.
#' The library is loaded with the package, by 'jlbind', so this is typically
#' because it has not been built yet, or was built for another version of
#' CausalStructures, in which case run [install_backend()].
#'
#' @return `NULL`, invisibly.
#' @export
#' @examples
#' if (julia_ready()) {
#'   setup()
#' }
setup <- function() {
  jlbind::check_bound("CausalStructures")
  invisible(NULL)
}

# A seed for the library's RNG, or `NULL` for an unseeded one.
make_rng <- function(seed) {
  if (is.null(seed)) NULL else as.numeric(seed)
}

.onLoad <- function(libname, pkgname) {
  jlbind::bind_client(pkgname)
}

.onAttach <- function(libname, pkgname) {
  if (!julia_ready()) {
    packageStartupMessage(
      "The compiled CausalStructures.jl library is not available. Run ",
      "install_backend() to build it, or setup() for details."
    )
  }
}

